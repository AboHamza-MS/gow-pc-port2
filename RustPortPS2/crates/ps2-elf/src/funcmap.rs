//! The Ghidra function map (`games/scus-97399/funcmap.csv`) parser.
//!
//! One-to-one port of `ElfParser::loadGhidraFunctionMap` from
//! `PS2Recomp/ps2xRecomp/src/lib/elf_parser.cpp`, including its filtering:
//! a function that does not start inside a code section is dropped, and an end
//! past the section is clamped (`ClampFunctionEndToSection`).

use crate::number::parse_number;
use crate::{ElfFile, Section};

/// One function boundary from the map.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FunctionMapEntry {
    pub name: String,
    pub start: u32,
    pub end: u32,
}

/// The parsed map, in the order the C++ side ends up using it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct FunctionMap {
    entries: Vec<FunctionMapEntry>,
    rejected_outside_executable: usize,
    rejected_invalid_range: usize,
    skipped_lines: usize,
}

impl FunctionMap {
    /// Parse a `Name,Start,End,Size` CSV, keeping only the boundaries that fall
    /// inside a code section of `elf`.
    ///
    /// The first line is always treated as a header, exactly like the C++ side.
    pub fn from_ghidra_csv(text: &str, elf: &ElfFile<'_>) -> Self {
        let mut map = Self::default();
        let mut lines = text.lines();
        let _header = lines.next();

        for line in lines {
            if line.is_empty() {
                continue;
            }
            let mut fields = line.split(',');
            let (Some(name), Some(start), Some(end), Some(_size)) =
                (fields.next(), fields.next(), fields.next(), fields.next())
            else {
                map.skipped_lines += 1;
                continue;
            };
            let (Ok(start), Ok(end)) = (parse_number(start), parse_number(end)) else {
                map.skipped_lines += 1;
                continue;
            };

            let Some(section) = elf.find_function_section_by_address(start) else {
                map.rejected_outside_executable += 1;
                continue;
            };
            let end = clamp_function_end(section, start, end);
            if end <= start {
                map.rejected_invalid_range += 1;
                continue;
            }
            map.entries.push(FunctionMapEntry { name: name.to_owned(), start, end });
        }

        map.finish();
        map
    }

    /// Sort and deduplicate the way the C++ loader does: by start, real names
    /// before auto-generated ones, then the widest range, then the name. Of two
    /// entries that start at the same address the first one wins.
    fn finish(&mut self) {
        if self.entries.is_empty() {
            return;
        }
        self.entries.sort_by(|a, b| {
            use std::cmp::Ordering;
            match a.start.cmp(&b.start) {
                Ordering::Equal => {}
                other => return other,
            }
            let a_auto = is_auto_generated_name(&a.name);
            let b_auto = is_auto_generated_name(&b.name);
            match (a_auto, b_auto) {
                (true, false) => Ordering::Greater,
                (false, true) => Ordering::Less,
                _ => a.end.cmp(&b.end).reverse().then_with(|| a.name.cmp(&b.name)),
            }
        });
        self.entries.dedup_by(|a, b| a.start == b.start);
    }

    pub fn entries(&self) -> &[FunctionMapEntry] {
        &self.entries
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn find(&self, start: u32) -> Option<&FunctionMapEntry> {
        self.entries.iter().find(|entry| entry.start == start)
    }

    /// Functions whose start was not inside a code section. They are dropped.
    pub fn rejected_outside_executable(&self) -> usize {
        self.rejected_outside_executable
    }

    /// Functions whose clamped range was empty. They are dropped.
    pub fn rejected_invalid_range(&self) -> usize {
        self.rejected_invalid_range
    }

    /// Lines that were not four fields or whose addresses did not parse.
    pub fn skipped_lines(&self) -> usize {
        self.skipped_lines
    }
}

/// `IsAutoGeneratedName`: names Ghidra or the analyzer invent.
pub fn is_auto_generated_name(name: &str) -> bool {
    name.starts_with("sub_") || name.starts_with("FUN_") || name.starts_with("LAB_") || name.starts_with("DAT_")
}

/// `ClampFunctionEndToSection`: keep the end inside the section, and guarantee
/// at least four bytes of function when the section allows it.
pub(crate) fn clamp_function_end(section: &Section<'_>, start: u32, requested_end: u32) -> u32 {
    let section_end_64 = u64::from(section.address) + u64::from(section.size);
    let section_end = if section_end_64 > u64::from(u32::MAX) { u32::MAX } else { section_end_64 as u32 };

    let mut end = requested_end;
    if end == 0 || end > section_end {
        end = section_end;
    }
    if end <= start {
        let minimum_end = u64::from(start) + 4;
        end = if minimum_end <= section_end_64 { minimum_end as u32 } else { section_end };
    }
    end
}

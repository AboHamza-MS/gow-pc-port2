//! `gen-call-list`: the syscall and stub name lists of the runtime (`ps2_call_list.h`, X-macros) as the Rust constants
//! the recompiler resolves function names against (`crates/ps2-recomp/src/calls_generated.rs`).

use std::path::Path;

/// `text` without its `/* ... */` comments and its `//` tail.
fn code_of(line: &str) -> String {
    let mut code = String::new();
    let mut rest = line;
    while let Some(at) = rest.find("/*") {
        code.push_str(&rest[..at]);
        match rest[at + 2..].find("*/") {
            Some(end) => rest = &rest[at + 2 + end + 2..],
            None => {
                code.push_str(&rest[at..]);
                rest = "";
                break;
            }
        }
    }
    code.push_str(rest);
    code.split("//").next().unwrap_or("").to_owned()
}

/// Every `X(name)` of `code` (the `X` not preceded by a word character).
fn entries(code: &str) -> Vec<String> {
    let bytes = code.as_bytes();
    let word = |b: u8| b.is_ascii_alphanumeric() || b == b'_';
    let mut names = Vec::new();
    let mut i = 0;
    while i + 2 < bytes.len() {
        if bytes[i] == b'X' && bytes[i + 1] == b'(' && (i == 0 || !word(bytes[i - 1])) {
            let start = i + 2;
            let mut end = start;
            while end < bytes.len() && word(bytes[end]) {
                end += 1;
            }
            if end > start && bytes.get(end) == Some(&b')') {
                names.push(code[start..end].to_owned());
                i = end + 1;
                continue;
            }
        }
        i += 1;
    }
    names
}

fn is_define(line: &str, macro_name: &str) -> bool {
    line.trim_start().strip_prefix("#define").is_some_and(|rest| {
        rest.starts_with(char::is_whitespace) && rest.trim_start().starts_with(&format!("{macro_name}(X)"))
    })
}

pub fn read_list(lines: &[&str], macro_name: &str) -> Result<Vec<String>, String> {
    let mut names = Vec::new();
    let mut in_list = false;
    for line in lines {
        if !in_list {
            if is_define(line, macro_name) {
                in_list = true;
            } else {
                continue;
            }
        }
        names.extend(entries(&code_of(line)));
        if !line.trim_end().ends_with('\\') {
            break;
        }
    }
    if names.is_empty() {
        return Err(format!("{macro_name} not found or empty"));
    }
    Ok(names)
}

fn emit(name: &str, items: &[String]) -> String {
    let body: String = items.iter().map(|item| format!("    \"{item}\",\n")).collect();
    format!("pub const {name}: &[&str] = &[\n{body}];\n")
}

/// The contents of `calls_generated.rs` for the header text `header`.
pub fn generate(header: &str) -> Result<String, String> {
    let lines: Vec<&str> = header.lines().collect();
    Ok([
        "//! Generated by `ps2-dev gen-call-list` from `ps2_call_list.h`. Do not edit.\n\n".to_owned(),
        emit("SYSCALL_NAMES", &read_list(&lines, "PS2_SYSCALL_LIST")?),
        "\n".to_owned(),
        emit("STUB_NAMES", &read_list(&lines, "PS2_STUB_LIST")?),
    ]
    .concat())
}

pub fn run(args: &[String]) -> i32 {
    let [source, target] = args else {
        eprintln!("usage: ps2-dev gen-call-list ps2_call_list.h calls_generated.rs");
        return 2;
    };
    let header = match std::fs::read_to_string(source) {
        Ok(text) => text,
        Err(error) => {
            eprintln!("{source}: {error}");
            return 1;
        }
    };
    match generate(&header)
        .and_then(|text| std::fs::write(Path::new(target), text).map_err(|e| format!("{target}: {e}")))
    {
        Ok(()) => {
            println!("wrote {target}");
            0
        }
        Err(message) => {
            eprintln!("{message}");
            1
        }
    }
}
